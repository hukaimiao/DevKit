export function translate(language, key) {
  return language === 'en' && Object.hasOwn(english, key) ? english[key] : key
}

export function translateError(language, message) {
  if (language === 'en') {
    for (const [pattern, replacement] of englishErrors) {
      if (pattern.test(message)) return message.replace(pattern, replacement)
    }
    return translate(language, message)
  }
  if (Object.hasOwn(chineseErrors, message)) return chineseErrors[message]
  if (message.startsWith('Invalid Quartz field: ')) return '无效的 Quartz 字段：' + message.slice(22)
  const separator = message.indexOf(': ')
  const label = message.slice(0, separator)
  return separator >= 0 && Object.hasOwn(chineseErrors, label) ? chineseErrors[label] + '：' + message.slice(separator + 2) : message
}

